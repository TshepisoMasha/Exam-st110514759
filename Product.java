    private void jProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jProcessActionPerformed


    /**
     * Shared Process logic - used by the PROCESS button and the Tools > Process menu item.
     */
   
        // Capture the customer name and the selected product
        String customerName = jCustomer.getText().trim();
        String productName = jComboProducts.getSelectedItem().toString();

        // Validate the inputs before calculating
        if (customerName.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the customer name.");
            return;
        }

        double price;
        try {
            price = Double.parseDouble(jTextField2.getText().trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Please enter a valid numeric price.");
            return;
        }

        // Calculate VAT, commission and total using the ProductCalculations class
        ProductCalculations calc = new ProductCalculations(price);

        String details = "Customer Name: " + customerName + "\n"
                + "Product: " + productName + "\n"
                + "VAT: R " + calc.GetVat() + "\n"
                + "COMMISSION: R " + calc.GetCommission() + "\n"
                + "TOTAL: R " + calc.GetTotal();

        // Display the output in a message box
        JOptionPane.showMessageDialog(this, details);

        // Save the same information to data.txt
        saveToFile(details);
    }

    
    private void saveToFile(String details) {
        try (PrintWriter writer = new PrintWriter(new FileWriter("data.txt"))) {
            writer.println("DATA LOG");
            writer.println("**********************************");
            writer.println(details);
            writer.println("**********************************");
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Could not save to data.txt: " + ex.getMessage());
        }
    }

